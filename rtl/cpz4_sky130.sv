// Standalone logical boundary. The default build uses fixed phase centers to
// leave area for the DCO and routing. Set ON_CHIP_CAL=1 for histogram calibration.
module cpz4_sky130 #(
    parameter ON_CHIP_CAL = 1'b0,
    parameter [7:0] MAX_COARSE_CODE = 8'd255,
    parameter TRACKING_REPLICAS = 1'b0
) (
    input  wire        VDD_CORE,
    input  wire        VDD_DCO,
    input  wire        VSS,
    input  wire        ref_clk,
    input  wire [23:0]  ctrl,
    output wire [11:0]  status,
    output wire        clk_out,
    output wire        clk_mon
);
    wire [254:0] therm;
    wire [127:0] fine_therm;
    wire [4:0] taps;
    wire [14:0] fine_taps;
    wire osc_enable;

    cpz4_pll #(.ON_CHIP_CAL(ON_CHIP_CAL), .MAX_COARSE_CODE(MAX_COARSE_CODE),
              .TRACKING_REPLICAS(TRACKING_REPLICAS)) controller(
                       .ref_clk(ref_clk), .reset_n(ctrl[22]), .enable(ctrl[21]),
                       .cfg_toggle(ctrl[20]), .cfg_addr(ctrl[19:17]), .cfg_data(ctrl[16:0]),
                       .dco_tap(taps), .dco_fine_tap(fine_taps), .dco_enable(osc_enable),
                       .dco_therm(therm), .dco_fine_therm(fine_therm),
                       .clk_out(clk_out), .clk_mon(clk_mon), .status(status));
    cpz4_dco oscillator(.vdd(VDD_DCO), .vss(VSS), .enable(osc_enable), .therm(therm),
                        .fine_therm(fine_therm), .tap(taps), .fine_tap(fine_taps));
endmodule

// Analog hard macro. Its transistor netlist is generated by spice/dco_deck.py.
(* blackbox *) module cpz4_dco (
    input  wire         vdd,
    input  wire         vss,
    input  wire         enable,
    input  wire [254:0] therm,
    input  wire [127:0] fine_therm,
    output wire [4:0]   tap,
    output wire [14:0]  fine_tap
);
endmodule
