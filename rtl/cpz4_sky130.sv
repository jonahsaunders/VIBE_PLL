// Standalone logical boundary. Pad cells and wrapper routes are harness views.
module cpz4_sky130 (
    input  wire        VDD_CORE,
    input  wire        VDD_DCO,
    input  wire        VSS,
    input  wire        ref_clk,
    input  wire [23:0]  ctrl,
    output wire [11:0]  status,
    output wire        clk_out,
    output wire        clk_mon
);
    wire [254:0] therm;
    wire [4:0] taps;
    wire osc_enable;

    cpz4_pll controller(.ref_clk(ref_clk), .reset_n(ctrl[22]), .enable(ctrl[21]),
                       .cfg_toggle(ctrl[20]), .cfg_addr(ctrl[19:17]), .cfg_data(ctrl[16:0]),
                       .dco_tap(taps), .dco_enable(osc_enable), .dco_therm(therm),
                       .clk_out(clk_out), .clk_mon(clk_mon), .status(status));
    cpz4_dco oscillator(.vdd(VDD_DCO), .vss(VSS), .enable(osc_enable), .therm(therm), .tap(taps));
endmodule

// Analog hard macro. Its transistor netlist is generated by spice/dco_deck.py.
(* blackbox *) module cpz4_dco (
    input  wire         vdd,
    input  wire         vss,
    input  wire         enable,
    input  wire [254:0] therm,
    output wire [4:0]   tap
);
endmodule
